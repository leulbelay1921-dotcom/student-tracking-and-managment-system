package com.sitms.evaluation;

import java.time.OffsetDateTime;
import java.util.UUID;

/** API view of an {@link Evaluation}. */
public record EvaluationResponse(
    UUID id,
    UUID studentId,
    UUID internshipId,
    UUID supervisorId,
    int technicalSkills,
    int communication,
    int teamwork,
    int problemSolving,
    int professionalism,
    String strengths,
    String improvement,
    String comments,
    int overallScore,
    EvaluationStatus status,
    Integer punctuality,
    Integer reliability,
    Integer independenceWork,
    Integer communicationSkills,
    Integer professionalConduct,
    Integer learningSpeed,
    Integer commitment,
    Integer accuracy,
    Integer teamContribution,
    Integer cooperation,
    Integer technicalProficiency,
    Integer organizationalSkills,
    Integer projectSupport,
    Integer taskResponsibility,
    Integer qualityTeamMember,
    String remarks,
    String department,
    String companyName,
    OffsetDateTime createdAt,
    OffsetDateTime updatedAt) {

  static EvaluationResponse from(Evaluation evaluation) {
    return new EvaluationResponse(
        evaluation.getId(),
        evaluation.getStudentId(),
        evaluation.getInternshipId(),
        evaluation.getSupervisorId(),
        evaluation.getTechnicalSkills(),
        evaluation.getCommunication(),
        evaluation.getTeamwork(),
        evaluation.getProblemSolving(),
        evaluation.getProfessionalism(),
        evaluation.getStrengths(),
        evaluation.getImprovement(),
        evaluation.getComments(),
        evaluation.getOverallScore(),
        evaluation.getStatus(),
        evaluation.getPunctuality(),
        evaluation.getReliability(),
        evaluation.getIndependenceWork(),
        evaluation.getCommunicationSkills(),
        evaluation.getProfessionalConduct(),
        evaluation.getLearningSpeed(),
        evaluation.getCommitment(),
        evaluation.getAccuracy(),
        evaluation.getTeamContribution(),
        evaluation.getCooperation(),
        evaluation.getTechnicalProficiency(),
        evaluation.getOrganizationalSkills(),
        evaluation.getProjectSupport(),
        evaluation.getTaskResponsibility(),
        evaluation.getQualityTeamMember(),
        evaluation.getRemarks(),
        evaluation.getDepartment(),
        evaluation.getCompanyName(),
        evaluation.getCreatedAt(),
        evaluation.getUpdatedAt());
  }
}